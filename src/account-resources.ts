export function deliveryStatusKey(
  status: string,
): 'pending' | 'leased' | 'retry' | 'sent' | 'failed' | 'unknownStatus' {
  return status === 'pending' ||
    status === 'leased' ||
    status === 'retry' ||
    status === 'sent' ||
    status === 'failed'
    ? status
    : 'unknownStatus';
}
